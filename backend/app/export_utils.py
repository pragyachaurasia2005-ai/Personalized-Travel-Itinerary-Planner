from typing import Dict, Any
from .models import TripItinerary

def trip_to_markdown(trip: TripItinerary) -> str:
    """Generates an aesthetic, shareable Markdown document from a TripItinerary."""
    cb = trip.cost_breakdown
    sym = trip.currency_symbol or "$"
    curr = trip.currency or "USD"

    md = []
    md.append(f"# 🌍 {trip.title}")
    md.append(f"**Destination:** {trip.destination} | **Duration:** {trip.duration_days} Days ({trip.start_date} to {trip.end_date})")
    md.append(f"**Traveler Style:** {trip.traveler_type.title()} (Party size: {trip.group_size}) | **Budget Tier:** {trip.budget_tier.title()}")
    md.append(f"**Engine:** {trip.generation_model} ({'Google Gemini AI' if trip.generation_source == 'gemini' else 'Adaptive Local Engine'})")
    md.append("")
    md.append("## 💡 AI Travel Rationale")
    md.append(f"> {trip.ai_rationale}")
    md.append("")
    md.append(f"## 💰 Estimated Cost Breakdown ({curr})")
    md.append(f"- **Accommodations:** {sym}{cb.stay:,.2f}")
    md.append(f"- **Dining & Culinary:** {sym}{cb.dining:,.2f}")
    md.append(f"- **Attractions & Experiences:** {sym}{cb.attractions:,.2f}")
    md.append(f"- **Transportation & Transit:** {sym}{cb.transport:,.2f}")
    md.append(f"- **Miscellaneous & Buffers:** {sym}{cb.misc:,.2f}")
    md.append(f"- **Total Estimated Cost:** **{sym}{cb.total:,.2f}** ({sym}{cb.per_person:,.2f} per person)")
    md.append("")
    md.append("---")
    md.append("## 🗓️ Day-by-Day Itinerary")
    md.append("")

    for day in trip.days:
        md.append(f"### Day {day.day_number}: {day.theme}")
        if day.date_str:
            md.append(f"*Date: {day.date_str}*")
        md.append(f"*{day.summary}*")
        md.append("")
        if day.accommodation_suggestion:
            md.append(f"🏨 **Recommended Stay:** {day.accommodation_suggestion}")
        if day.travel_logistics_note:
            md.append(f"🚆 **Transit & Route:** {day.travel_logistics_note}")
        md.append("")

        for act in day.activities:
            cat_icon = {
                "attraction": "🏛️",
                "dining": "🍽️",
                "accommodation": "🏨",
                "transportation": "🚆",
                "experience": "🌿",
                "relaxation": "🧘"
            }.get(act.category, "📍")

            md.append(f"#### {cat_icon} {act.time_str} — {act.title}")
            md.append(f"- **Location:** {act.location_name}")
            md.append(f"- **Est. Cost:** {sym}{act.estimated_cost:,.2f}")
            md.append(f"- **Overview:** {act.description}")
            if act.booking_tip:
                md.append(f"- **Insider Tip:** {act.booking_tip}")
            if act.transport_recommendation:
                md.append(f"- **How to Get There:** {act.transport_recommendation}")
            md.append("")

        md.append("---")

    md.append("## 🎒 Recommended Packing Checklist")
    for item in trip.packing_checklist:
        md.append(f"- [ ] {item}")
    md.append("")

    md.append("## 📌 Local Etiquette & Pro Tips")
    for tip in trip.local_etiquette_tips:
        md.append(f"- {tip}")
    md.append("")
    md.append(f"*Generated by Personalized Travel Itinerary Planner ({trip.generation_model})*")

    return "\n".join(md)
